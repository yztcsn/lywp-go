#!/usr/bin/env bash
# LYWP installer for Debian 12 (also works on other systemd-based distros).
set -euo pipefail

APP_DIR="/opt/lywp"
DATA_DIR="/var/lib/lywp"
CONF_DIR="/etc/lywp"
CONF_FILE="$CONF_DIR/config.json"
UNIT_FILE="/etc/systemd/system/lywp.service"
CMD_FILE="/usr/local/bin/lywp"
BIN_FILE="$APP_DIR/lywp-server"
SOURCE_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"

green() { printf '\033[32m%s\033[0m\n' "$*"; }
yellow() { printf '\033[33m%s\033[0m\n' "$*"; }
red() { printf '\033[31m%s\033[0m\n' "$*" >&2; }
die() { red "$*"; exit 1; }

[[ $EUID -eq 0 ]] || die "请使用 root 运行：sudo bash install.sh"
[[ -f /etc/debian_version ]] || yellow "当前系统不是 Debian，仍将继续尝试安装。"
if ! command -v go >/dev/null 2>&1; then
  if [[ -x /usr/local/go/bin/go ]]; then
    export PATH="/usr/local/go/bin:$PATH"
  fi
fi
command -v systemctl >/dev/null 2>&1 || die "未检测到 systemd，无法注册开机启动服务。"

if [[ -f "$UNIT_FILE" && "${FORCE:-0}" != "1" ]]; then
  die "检测到已安装的 lywp 服务。请先运行 bash uninstall.sh，或使用 FORCE=1 bash install.sh 覆盖。"
fi

echo
green "=== LYWP · Go 版网盘安装 ==="
echo

# ---- interactive inputs (environment variables can pre-fill) ----
read_input() {
  local prompt="$1" var="$2" default="${3:-}"
  local value
  if [[ -n "${!var:-}" ]]; then
    value="${!var}"
  else
    IFS= read -r -p "$prompt" value
    value="${value:-$default}"
  fi
  printf -v "$var" '%s' "$value"
}

read_input "网盘名称（显示在页面上）[老杨网盘]: " SITE_NAME "老杨网盘"

# ---- netdisk root directory (where uploaded files actually land) ----
STORAGE_DIR="${LYWP_STORAGE_ROOT:-}"
read_input "网盘主目录（上传的文件都放在这里）[$DATA_DIR/files]: " STORAGE_DIR "$DATA_DIR/files"
[[ "$STORAGE_DIR" == /* ]] || die "网盘主目录必须是绝对路径（以 / 开头）。"
while [[ ${#STORAGE_DIR} -gt 1 && "$STORAGE_DIR" == */ ]]; do
  STORAGE_DIR="${STORAGE_DIR%/}"
done
case "$STORAGE_DIR" in
  /|/bin|/boot|/dev|/etc|/home|/lib|/lib64|/media|/mnt|/opt|/proc|/root|/run|/sbin|/srv|/sys|/tmp|/usr|/var)
    die "不能直接使用系统目录 $STORAGE_DIR 作为网盘主目录，请指定它的一个子目录。"
    ;;
esac
case "$DATA_DIR/" in
  "$STORAGE_DIR"/*)
    die "网盘主目录不能包含内部数据目录 $DATA_DIR（否则数据库会显示在网盘里），请改用更下层的子目录。"
    ;;
esac
if [[ -e "$STORAGE_DIR" && ! -d "$STORAGE_DIR" ]]; then
  die "网盘主目录已存在但不是文件夹：$STORAGE_DIR"
fi
if ! mkdir -p "$STORAGE_DIR"; then
  die "无法创建网盘主目录：$STORAGE_DIR"
fi
if ! : > "$STORAGE_DIR/.lywp_write_test"; then
  die "网盘主目录不可写：$STORAGE_DIR"
fi
rm -f "$STORAGE_DIR/.lywp_write_test"

PORT=""
read_input "监听端口 [8080]: " PORT "8080"
[[ "$PORT" =~ ^[0-9]+$ ]] && (( PORT >= 1 && PORT <= 65535 )) || die "端口必须是 1-65535 的数字。"

if command -v ss >/dev/null 2>&1; then
  if ss -ltn "( sport = :$PORT )" 2>/dev/null | grep -q ":$PORT "; then
    yellow "警告：端口 $PORT 当前已被占用。"
  fi
fi

if [[ -n "${LYWP_PASSWORD:-}" ]]; then
  PASSWORD="$LYWP_PASSWORD"
else
  while true; do
    read -r -s -p "访问密码（必填）: " PASSWORD
    echo
    [[ -n "$PASSWORD" ]] && break
    red "密码不能为空。"
  done
  read -r -s -p "再输入一次密码: " PASSWORD2
  echo
  [[ "$PASSWORD" == "$PASSWORD2" ]] || die "两次输入的密码不一致。"
fi

echo
echo "安装目录:   $APP_DIR"
echo "网盘主目录: $STORAGE_DIR（上传的文件都放在这里）"
echo "内部数据:   $DATA_DIR（SQLite 数据库与会话）"
echo "配置文件:   $CONF_FILE"
echo "端口:       $PORT"
echo

# ---- build ----
green "[1/5] 准备目录并安装 Go 程序..."
mkdir -p "$APP_DIR/src" "$DATA_DIR/tmp" "$CONF_DIR"
cp -a "$SOURCE_DIR"/. "$APP_DIR/src/"
rm -f "$APP_DIR/src/lywp-server" "$APP_DIR/src/lywp-server.exe"
# Keep release archives and git metadata out of the installed source tree.
rm -rf "$APP_DIR/src/dist" "$APP_DIR/src/.git"

case "$(uname -m)" in
  x86_64|amd64) ARCH="amd64" ;;
  aarch64|arm64) ARCH="arm64" ;;
  *) ARCH="" ;;
esac

PREBUILT="$SOURCE_DIR/bin/lywp-server-linux-$ARCH"
if [[ -n "$ARCH" && -f "$PREBUILT" ]]; then
  echo "使用预编译二进制（linux-$ARCH）"
  cp "$PREBUILT" "$BIN_FILE"
else
  command -v go >/dev/null 2>&1 || die "未检测到 Go，请先安装 Go 环境。"
  echo "未找到对应架构的预编译包，使用本机 Go 编译..."
  (
    cd "$APP_DIR/src"
    CGO_ENABLED=0 go build -trimpath -ldflags="-s -w" -o "$BIN_FILE" .
  )
fi
chmod 750 "$BIN_FILE"

# aria2 backs magnet/torrent/FTP offline downloads. Install it up front so
# those tasks work without manual setup; failures are non-fatal because the
# server also retries installation on demand.
if ! command -v aria2c >/dev/null 2>&1; then
  echo "准备离线下载依赖 aria2..."
  if ! DEBIAN_FRONTEND=noninteractive apt-get install -y -qq aria2 >/dev/null 2>&1; then
    if ! DEBIAN_FRONTEND=noninteractive apt-get update -qq >/dev/null 2>&1 || \
       ! DEBIAN_FRONTEND=noninteractive apt-get install -y -qq aria2 >/dev/null 2>&1; then
      yellow "aria2 安装失败，磁力/FTP 离线下载将在首次使用时重试。可手动执行：apt-get install -y aria2"
    fi
  fi
fi

# ---- config (hash generated by the binary; no plaintext stored) ----
green "[2/5] 写入配置（密码只保存哈希）..."
LYWP_CONFIG="$CONF_FILE" \
LYWP_NAME="$SITE_NAME" \
LYWP_PORT="$PORT" \
LYWP_PASSWORD="$PASSWORD" \
LYWP_DATA_DIR="$DATA_DIR" \
LYWP_STORAGE_ROOT="$STORAGE_DIR" \
  "$BIN_FILE" init-config
chmod 700 "$CONF_FILE"
unset PASSWORD PASSWORD2 LYWP_PASSWORD

# ---- systemd unit ----
green "[3/5] 注册 systemd 服务（开机自启）..."
cat > "$UNIT_FILE" <<EOF
[Unit]
Description=LYWP Go Netdisk
Documentation=https://github.com/niiter/lywp-go
After=network-online.target
Wants=network-online.target

[Service]
Type=simple
WorkingDirectory=$APP_DIR
ExecStart=$BIN_FILE serve --config $CONF_FILE
Restart=always
RestartSec=3
LimitNOFILE=1048576
StandardOutput=journal
StandardError=journal

[Install]
WantedBy=multi-user.target
EOF
chmod 644 "$UNIT_FILE"

# ---- lywp shortcut command ----
green "[4/5] 注册快捷命令 lywp..."
cat > "$CMD_FILE" <<'EOF'
#!/usr/bin/env bash
# LYWP service controller
SERVICE="lywp.service"
case "${1:-}" in
  start)   systemctl start "$SERVICE" ;;
  stop)    systemctl stop "$SERVICE" ;;
  restart|resatrt) systemctl restart "$SERVICE" ;;
  status)  systemctl status "$SERVICE" --no-pager ;;
  log)
    shift
    if [[ "${1:-}" == "--no-follow" ]]; then
      journalctl -u "$SERVICE" -n 200 --no-pager
    else
      journalctl -u "$SERVICE" -n 100 -f "$@"
    fi
    ;;
  *)
    echo "用法: lywp {start|stop|restart|resatrt|status|log [--no-follow]}"
    exit 2
    ;;
esac
EOF
chmod 755 "$CMD_FILE"

# ---- start ----
green "[5/5] 启动服务..."
systemctl daemon-reload
systemctl enable lywp.service >/dev/null
systemctl restart lywp.service

if systemctl is-active --quiet lywp.service; then
  echo
  green "安装完成！"
  echo "  网盘名称: $SITE_NAME"
  echo "  网盘主目录: $STORAGE_DIR"
  echo "  访问地址: http://服务器IP:$PORT/"
  echo "  分享页面: http://服务器IP:$PORT/share.html"
  echo
  echo "快捷命令:"
  echo "  lywp start | stop | restart | resatrt | status | log"
  echo
  yellow "提示：请放行防火墙端口 $PORT（例如 ufw allow $PORT/tcp）。"
else
  red "服务未能正常启动，请执行 lywp log 查看日志。"
  exit 1
fi
